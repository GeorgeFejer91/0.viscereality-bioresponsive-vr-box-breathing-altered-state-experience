#!/usr/bin/env python3
"""Run the preregistered order-adjusted repeated-measures ANCOVA candidate.

INTERNAL CANDIDATE ONLY. This script reads the authoritative OSF master dataset
but refuses to write into that repository. Its output must be reviewed, adopted,
and regenerated by the OSF package maintainer before manuscript use.

The registered omnibus condition test is implemented as a partial F test that
compares these nested ordinary least-squares models on complete within-subject
triplets:

    reduced: value ~ participant + numeric block position
    full:    value ~ participant + numeric block position + condition

Participant fixed effects provide the repeated-measures blocking. The two added
condition indicators test the three-level within-subject condition effect after
adjustment for the block position at which each condition was presented.
"""

from __future__ import annotations

import argparse
import hashlib
